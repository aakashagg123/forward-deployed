#!/usr/bin/env python3
"""Post-build audit for the generated site in dist/.

Checks:
  1. No internal link points at a README.html. Pages under learning-zone/ are
     reported separately: they are generated by the gatsby repo and their
     README.html files are real pages there, not legacy URLs.
  2. No internal href/src resolves to a missing file.
  3. Every README.md under content/<space>/ has a README.html redirect stub
     (canonical + meta refresh) next to its index.html in dist/.
  4. No "Was this helpful" widget anywhere in the generated pages.

Usage: python3 scripts/audit_site.py [dist_dir]   (exit code 1 on any failure)
"""
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urldefrag, urlparse, unquote

ROOT = Path(__file__).resolve().parent.parent
DIST = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "dist"
CONTENT = ROOT / "content"
SITE_HOSTS = {"forward-deployed.in", "www.forward-deployed.in"}
# <link rel=...> values that are not navigations/resources worth resolving.
SKIP_LINK_RELS = {"preconnect", "dns-prefetch"}


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.found = []  # (tag, attr, value)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "link" and set((a.get("rel") or "").split()) & SKIP_LINK_RELS:
            return
        for attr in ("href", "src"):
            if a.get(attr):
                self.found.append((tag, attr, a[attr]))


def resolve(page: Path, value: str):
    """Return the dist file an internal URL points at, or None if external/ignorable."""
    value, _ = urldefrag(value.strip())
    if not value:
        return None
    u = urlparse(value)
    if u.scheme in ("mailto", "tel", "javascript", "data"):
        return None
    if u.scheme in ("http", "https"):
        if u.netloc not in SITE_HOSTS:
            return None
        rel = u.path
        target = DIST / unquote(rel).lstrip("/")
    elif u.netloc:  # protocol-relative
        return None
    elif value.startswith("/"):
        target = DIST / unquote(u.path).lstrip("/")
    else:
        target = (page.parent / unquote(u.path)).resolve()
    if u.path.endswith("/") or u.path == "":
        target = target / "index.html" if u.path else page
    elif target.is_dir():
        target = target / "index.html"
    return target


def main():
    if not DIST.is_dir():
        print(f"dist not found: {DIST} (run `npm run build` first)")
        return 1

    failures = []
    pages = sorted(DIST.rglob("*.html"))
    stubs = {p for p in pages if p.name == "README.html"}

    readme_links, lz_readme_links, missing = [], [], []
    for page in pages:
        parser = Links()
        parser.feed(page.read_text(encoding="utf-8", errors="replace"))
        for tag, attr, value in parser.found:
            path_part = urlparse(urldefrag(value)[0]).path
            is_internal = not urlparse(value).scheme or urlparse(value).netloc in SITE_HOSTS
            if is_internal and path_part.endswith("README.html") and page not in stubs:
                in_lz = page.relative_to(DIST).parts[0] == "learning-zone"
                (lz_readme_links if in_lz else readme_links).append((page, value))
            target = resolve(page, value)
            if target is not None and not target.exists():
                missing.append((page, value))

    # Check 1
    print(f"[1] internal links to README.html (site pages): {len(readme_links)}")
    print(f"    info: {len(lz_readme_links)} README.html links inside learning-zone/ (gatsby-generated, not counted)")
    for page, value in readme_links[:20]:
        print(f"    {page.relative_to(DIST)} -> {value}")
    if readme_links:
        failures.append("README.html links")

    # Check 2
    print(f"[2] internal links to missing files: {len(missing)} (across {len(pages)} pages)")
    for page, value in missing[:40]:
        print(f"    {page.relative_to(DIST)} -> {value}")
    if missing:
        failures.append("missing link targets")

    # Check 3
    bad_stubs = []
    sources = sorted(CONTENT.glob("*/**/README.md"))
    for src in sources:
        rel = src.relative_to(CONTENT)
        stub = DIST / rel.parent / "README.html"
        index = DIST / rel.parent / "index.html"
        text = stub.read_text(encoding="utf-8") if stub.exists() else ""
        ok = (
            stub.exists()
            and index.exists()
            and '<link rel="canonical" href="./">' in text
            and '<meta http-equiv="refresh" content="0; url=./">' in text
        )
        if not ok:
            bad_stubs.append(str(rel))
    print(f"[3] README.md sources: {len(sources)}, missing or invalid redirect stubs: {len(bad_stubs)}")
    for r in bad_stubs:
        print(f"    {r}")
    if bad_stubs:
        failures.append("redirect stubs")

    # Check 4
    helpful = [p for p in pages if "Was this helpful" in p.read_text(encoding="utf-8", errors="replace")]
    print(f"[4] pages containing 'Was this helpful': {len(helpful)}")
    for p in helpful[:10]:
        print(f"    {p.relative_to(DIST)}")
    if helpful:
        failures.append("feedback widget")

    print("PASS" if not failures else f"FAIL: {', '.join(failures)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
